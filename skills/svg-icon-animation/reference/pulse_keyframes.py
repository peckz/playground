"""
Generate the keyframes for a wave traveling down a stroked outline (the bookmark ribbon).

Three tracks:
  body   - body path morph: an outward Gaussian bulge slides down both sides
  hem    - hem group transform: scaleX derived from the bulge at the seam, scaleY sag
  notch  - hem path morph: the V apex dips and bounces (damped sine)

The path morphs run as SMIL <animate>, since Safari can't animate CSS `d`. The hem
transform stays a CSS @keyframes block.

Run:  python3 skills/svg-icon-animation/reference/pulse_keyframes.py ts > bookmarkMorph.ts
      python3 skills/svg-icon-animation/reference/pulse_keyframes.py css
Paste the css output (bookmarkHem) into the icon's stylesheet. The 0% body path must equal the JSX d.
The geometry is for a 48-unit bookmark icon: change the constants below for your own outline.

Why it looks smooth: SMIL interpolates `d` linearly between frames, so the wave centre
is sampled every 4% along a sine ease and the amplitude follows a smoothstep envelope.
Why it stays crisp: every generated path at amplitude 0 is collinear cubics, identical to
a straight line, and the seam node keeps a vertical tangent so nothing kinks.
"""

import math
import sys

Y_TOP, Y_BOT, SEG = 12.0, 40.114, 6
NODE_YS = [Y_BOT - (Y_BOT - Y_TOP) * index / SEG for index in range(SEG + 1)]  # bottom -> top
WAVE_WIDTH = 7.0
AMPLITUDE = 4.2
WAVE_START_PCT, WAVE_END_PCT = 12, 84  # the wave centre travels y 4 -> 54 between these
SAMPLE_STEP_PCT = 4


def bump(y, amplitude, centre):
    gaussian = math.exp(-((y - centre) / WAVE_WIDTH) ** 2)
    value = amplitude * gaussian
    slope = value * (-2 * (y - centre) / WAVE_WIDTH**2)
    return value, slope


def side_nodes(base_x, sign, amplitude, centre):
    nodes = []
    for index, y in enumerate(NODE_YS):
        offset, slope = bump(y, amplitude, centre)
        if index == 0 or index == SEG:
            slope = 0.0  # seam and corner may widen, but their tangents stay vertical
        nodes.append((base_x + sign * offset, y, sign * slope))
    return nodes


def cubics(nodes):
    parts = []
    for (x0, y0, slope0), (x1, y1, slope1) in zip(nodes, nodes[1:]):
        dy = y1 - y0
        control1 = (x0 + slope0 * dy / 3, y0 + dy / 3)
        control2 = (x1 - slope1 * dy / 3, y1 - dy / 3)
        parts.append(
            f"C{control1[0]:.4g} {control1[1]:.4g} {control2[0]:.4g} {control2[1]:.4g} {x1:.4g} {y1:.5g}"
        )
    return "".join(parts)


def body_path(amplitude, centre):
    left = side_nodes(10, -1, amplitude, centre)
    right = side_nodes(38, 1, amplitude, centre)
    left_top_x = left[-1][0]
    right_top_x = right[-1][0]
    return (
        f"M{left[0][0]:.4g} 40.114"
        + cubics(left)
        + f"C{left_top_x:.4g} 8.6863 12.6863 6 16 6H32C35.3137 6 {right_top_x:.4g} 8.6863 {right_top_x:.4g} 12"
        + cubics(right[::-1])
    )


def hem_path(apex_y):
    return (
        "M10 40.114C10 41.74 11.8387 42.687 13.1625 41.741"
        f"L24 {apex_y:.4g}L34.8375 41.741C36.1613 42.687 38 41.74 38 40.114"
    )


def ease_in_out_sine(t):
    return 0.5 - 0.5 * math.cos(math.pi * t)


def smoothstep(t):
    t = max(0.0, min(1.0, t))
    return t * t * (3 - 2 * t)


def wave_at(pct):
    if pct < WAVE_START_PCT or pct > WAVE_END_PCT:
        return 0.0, 60.0
    t = (pct - WAVE_START_PCT) / (WAVE_END_PCT - WAVE_START_PCT)
    centre = 4 + 50 * ease_in_out_sine(t)
    envelope = smoothstep(t / 0.18) * (1 - smoothstep((t - 0.62) / 0.38))
    return AMPLITUDE * envelope, centre


HIT_PCT = next(pct for pct in range(WAVE_START_PCT, WAVE_END_PCT + 1) if wave_at(pct)[1] >= Y_BOT)

# hem body: a light sag around the moment the wave crosses the seam
SAG_SCHEDULE = [
    (0, 1),
    (HIT_PCT - 9, 1),
    (HIT_PCT - 1, 0.95),
    (HIT_PCT + 6, 1.08),
    (HIT_PCT + 15, 0.98),
    (HIT_PCT + 23, 1.01),
    (100, 1),
]


def sag_at(pct):
    for (pct0, value0), (pct1, value1) in zip(SAG_SCHEDULE, SAG_SCHEDULE[1:]):
        if pct0 <= pct <= pct1:
            return value0 + (value1 - value0) * ease_in_out_sine((pct - pct0) / (pct1 - pct0))
    return 1


NOTCH_START_PCT = HIT_PCT + 1


def apex_at(pct):
    """The wave runs in along the V arms, so the apex dips a beat after the corners. +y is down."""
    if pct <= NOTCH_START_PCT or pct >= 100:
        return 34.0
    q = pct - NOTCH_START_PCT
    return 34 + 4.5 * math.exp(-q / 13) * math.sin(math.pi * q / 15)


def print_ts(pcts):
    print("// Generated by skills/svg-icon-animation/reference/pulse_keyframes.py, don't edit by hand")
    print("")
    print("/** Where each frame sits in the play, 0-1, for SMIL keyTimes */")
    times = ";".join(f"{pct / 100:g}" for pct in pcts)
    print(f'export const BOOKMARK_KEY_TIMES = "{times}";')
    print("")
    print("/** Body outline: a bulge slides down both sides */")
    print("export const BOOKMARK_BODY_FRAMES = [")
    for pct in pcts:
        amplitude, centre = wave_at(pct)
        print(f'  "{body_path(amplitude, centre)}",')
    print('].join(";");')
    print("")
    print("/** Hem: the V apex dips a beat later, then bounces out */")
    print("export const BOOKMARK_NOTCH_FRAMES = [")
    for pct in pcts:
        print(f'  "{hem_path(apex_at(pct))}",')
    print('].join(";");')


def main():
    pcts = list(range(0, 101, SAMPLE_STEP_PCT))
    if pcts[-1] != 100:
        pcts.append(100)

    if sys.argv[1:] == ["ts"]:
        print_ts(pcts)
        return

    print("@keyframes bookmarkHem {")
    for pct in pcts:
        amplitude, centre = wave_at(pct)
        scale_x = 1 + bump(Y_BOT, amplitude, centre)[0] / 14
        print(f"  {pct}% {{\n    transform: scale({scale_x:.4g}, {sag_at(pct):.4g});\n  }}")
    print("}")

    print(f"\n/* wave crosses the seam at {HIT_PCT}%, notch bounce starts at {NOTCH_START_PCT}% */")


if __name__ == "__main__":
    main()
